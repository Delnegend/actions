import importlib.util
import os
from pathlib import Path
import subprocess
import tempfile
import unittest

SCRIPT = Path(__file__).with_name('common-configs.py').resolve()
spec = importlib.util.spec_from_file_location('common_configs', SCRIPT)
scanner = importlib.util.module_from_spec(spec)
spec.loader.exec_module(scanner)


def lint_table(header='lints.clippy'):
    return (f'[{header}]\n' +
            ''.join(f'{key} = {{ level = "deny", priority = -1 }}\n' for key in scanner.CLIPPY_DENIED_GROUPS) +
            ''.join(f'{key} = "deny"\n' for key in scanner.CLIPPY_DENIED_LINTS))


PROFILE = '[profile.release]\nlto = "thin"\ncodegen-units = 1\nstrip = true\n'


class ConfigScanTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        self.git('init', '-q')
        self.write('clippy.toml', 'allow-unwrap-in-tests = true\nallow-expect-in-tests = true\nallow-panic-in-tests = true\nallow-indexing-slicing-in-tests = true\n')
        self.write('.cargo/config.toml', '[registry]\nglobal-min-publish-age = "14 days"\n[resolver]\nincompatible-publish-age = "deny"\n')

    def git(self, *args):
        return subprocess.run(['git', '-C', str(self.root), *args], check=True, capture_output=True)

    def write(self, path, data):
        target = self.root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(data)

    def package(self, directory='.', extra='', lints=None):
        name = 'pkg_' + directory.replace('/', '_').replace('.', 'root').replace('-', '_')
        prefix = '' if directory == '.' else directory + '/'
        self.write(prefix + 'Cargo.toml', f'[package]\nname = "{name}"\nversion = "0.1.0"\nedition = "2021"\n' + extra + (lint_table() if lints is None else lints))
        self.write(prefix + 'src/lib.rs', 'pub fn fixture() {}\n')

    def run_scan(self):
        self.git('add', '-A')
        return subprocess.run(['python3', str(SCRIPT), '--root', str(self.root)], text=True, capture_output=True)

    def assert_pass(self, result):
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)

    def test_standalone_and_unchanged_files(self):
        self.package(extra=PROFILE)
        before = (self.root / 'Cargo.toml').read_bytes()
        self.assert_pass(self.run_scan())
        self.assertEqual(before, (self.root / 'Cargo.toml').read_bytes())
        self.assertFalse((self.root / 'Cargo.lock').exists())

    def test_existing_lockfile_is_unchanged(self):
        self.package(extra=PROFILE)
        self.write('Cargo.lock', '# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = "pkg_root"\nversion = "0.1.0"\n')
        lockfile = self.root / 'Cargo.lock'
        before = lockfile.read_bytes()
        self.assert_pass(self.run_scan())
        self.assertEqual(before, lockfile.read_bytes())

    def test_virtual_workspace_globs_inheritance_and_path_dependency(self):
        self.write('Cargo.toml', '[workspace]\nresolver = "2"\nmembers = ["crates/*"]\n' + PROFILE + lint_table('workspace.lints.clippy'))
        self.package('crates/a', extra='[dependencies]\npkg_crates_b = { path = "../b" }\n', lints='[lints]\nworkspace = true\n')
        self.package('crates/b')
        self.assert_pass(self.run_scan())
        self.assertFalse((self.root / 'Cargo.lock').exists())

    def test_excluded_and_nested_workspaces(self):
        self.write('Cargo.toml', '[workspace]\nmembers = ["member"]\nexclude = ["excluded", "nested"]\n' + PROFILE)
        self.package('member')
        self.package('excluded', extra=PROFILE)
        self.write('nested/Cargo.toml', '[workspace]\nmembers = ["child"]\n' + PROFILE)
        self.package('nested/child')
        self.assert_pass(self.run_scan())

    def test_required_config_files_are_tracked_and_present(self):
        self.package(extra=PROFILE)
        self.git('add', 'Cargo.toml', 'src/lib.rs')
        result = subprocess.run(['python3', str(SCRIPT), '--root', str(self.root)], text=True, capture_output=True)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('clippy.toml', result.stdout)
        self.assertIn('.cargo/config.toml', result.stdout)
        self.git('add', 'clippy.toml', '.cargo/config.toml')
        (self.root / 'clippy.toml').unlink()
        result = subprocess.run(['python3', str(SCRIPT), '--root', str(self.root)], text=True, capture_output=True)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('clippy.toml', result.stdout)

    def test_config_values_and_malformed_toml(self):
        self.package(extra=PROFILE)
        cases = (
            ('clippy.toml', 'allow-unwrap-in-tests', 'false'),
            ('clippy.toml', 'allow-expect-in-tests', 'false'),
            ('clippy.toml', 'allow-panic-in-tests', 'false'),
            ('clippy.toml', 'allow-indexing-slicing-in-tests', 'false'),
            ('.cargo/config.toml', 'global-min-publish-age', '"7 days"'),
            ('.cargo/config.toml', 'incompatible-publish-age', '"allow"'),
        )
        for path, key, bad in cases:
            with self.subTest(key=key):
                file = self.root / path
                original = file.read_text()
                lines = original.splitlines(keepends=True)
                file.write_text(''.join(f'{key} = {bad}\n' if line.startswith(key + ' ') else line for line in lines))
                result = self.run_scan()
                self.assertNotEqual(result.returncode, 0)
                self.assertIn(path, result.stdout)
                self.assertIn(key, result.stdout)
                file.write_text(original)
        for path in ('clippy.toml', '.cargo/config.toml'):
            with self.subTest(path=path):
                file = self.root / path
                original = file.read_text()
                file.write_text('[invalid')
                result = self.run_scan()
                self.assertNotEqual(result.returncode, 0)
                self.assertIn(path, result.stdout)
                self.assertIn('cannot read or parse', result.stdout)
                file.write_text(original)

    def test_bun_quarantine_and_exemptions(self):
        self.write('frontend/bun.lock', '{}')
        self.write('frontend/bunfig.toml', '[install]\nminimumReleaseAge = 1814400\nminimumReleaseAgeExcludes = ["critical-fix"]\n[extra]\nvalue = true\n')
        result = self.run_scan()
        self.assert_pass(result)
        self.assertIn('frontend/bunfig.toml', result.stdout)
        self.assertIn('critical-fix', result.stdout)

    def test_bun_missing_invalid_and_weak_config(self):
        self.write('nested/bun.lockb', '')
        result = self.run_scan()
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('nested/bunfig.toml', result.stdout)
        for content in ('[install]\nminimumReleaseAge = 1209599\n',
                        '[install]\nminimumReleaseAge = true\n',
                        '[install]\nminimumReleaseAge = "1209600"\n',
                        '[install]\n', '[bad'):
            with self.subTest(content=content):
                self.write('nested/bunfig.toml', content)
                result = self.run_scan()
                self.assertNotEqual(result.returncode, 0)
                self.assertIn('nested/bunfig.toml', result.stdout)
                self.assertIn('cannot read or parse' if content == '[bad' else 'minimumReleaseAge', result.stdout)
        self.write('nested/bunfig.toml', '[install]\nminimumReleaseAge = 1209600\n')
        self.assert_pass(self.run_scan())

    def test_bun_ignores_untracked_lockfiles_and_node_projects(self):
        self.write('bun.lock', '{}')
        self.write('package.json', '{}')
        self.git('add', 'package.json')
        result = subprocess.run(['python3', str(SCRIPT), '--root', str(self.root)], text=True, capture_output=True)
        self.assert_pass(result)
        self.assertNotIn('minimumReleaseAge', result.stdout)

    def test_multiple_bun_lockfiles_report_independent_errors(self):
        self.write('a/bun.lock', '{}')
        self.write('b/bun.lock', '{}')
        result = self.run_scan()
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('a/bunfig.toml', result.stdout)
        self.assertIn('b/bunfig.toml', result.stdout)

    def test_no_rust_and_missing_manifest(self):
        self.write('ignored.rs', '')
        result = subprocess.run(['python3', str(SCRIPT), '--root', str(self.root)], text=True, capture_output=True)
        self.assert_pass(result)
        self.assertIn('No tracked Rust', result.stdout)
        result = self.run_scan()
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('no manifest is tracked', result.stdout)

    def test_malformed_missing_and_symlink_manifests(self):
        self.write('bad/Cargo.toml', '[broken')
        self.package('missing')
        self.git('add', '-A')
        (self.root / 'missing/Cargo.toml').unlink()
        (self.root / 'link').mkdir()
        os.symlink('../bad/Cargo.toml', self.root / 'link/Cargo.toml')
        self.git('add', 'link')
        result = subprocess.run(['python3', str(SCRIPT), '--root', str(self.root)], text=True, capture_output=True)
        self.assertNotEqual(result.returncode, 0)
        for text in ('bad/Cargo.toml', 'missing/Cargo.toml', 'link/Cargo.toml', 'symlink'):
            self.assertIn(text, result.stdout)

    def test_untracked_workspace_member_fails(self):
        self.write('Cargo.toml', '[workspace]\nmembers = ["member"]\n' + PROFILE)
        self.package('member')
        self.git('add', 'Cargo.toml')
        result = subprocess.run(['python3', str(SCRIPT), '--root', str(self.root)], text=True, capture_output=True)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('member/Cargo.toml', result.stdout)
        self.assertIn('not tracked', result.stdout)

    def test_policy_errors_and_priorities(self):
        self.package(extra=PROFILE)
        f = self.root / 'Cargo.toml'
        base = f.read_text()
        cases = {
            'pedantic': ('priority = -1', 'priority = 0'),
            'unwrap_used': ('unwrap_used = "deny"', 'unwrap_used = "allow"'),
            'expect_used': ('expect_used = "deny"', 'expect_used = { level = "deny", priority = -1 }'),
            'indexing_slicing': ('indexing_slicing = "deny"\n', ''),
            'opt-level': ('[profile.release]', '[profile.release]\nopt-level = 2'),
            'lto': ('lto = "thin"', 'lto = false'),
            'codegen-units': ('codegen-units = 1', 'codegen-units = 2'),
            'strip': ('strip = true', 'strip = false'),
        }
        for key, (old, new) in cases.items():
            with self.subTest(key=key):
                f.write_text(base.replace(old, new, 1))
                result = self.run_scan()
                self.assertNotEqual(result.returncode, 0, result.stdout)
                self.assertIn('Cargo.toml', result.stdout)
                self.assertIn(key, result.stdout)
        f.write_text(base.replace('strip = true', 'strip = false').replace('unwrap_used = "deny"', 'unwrap_used = "allow"'))
        result = self.run_scan()
        self.assertIn('profile.release.strip', result.stdout)
        self.assertIn('lints.clippy.unwrap_used', result.stdout)

    def test_alternative_valid_values(self):
        self.package(extra=PROFILE.replace('strip = true', 'strip = "symbols"\nopt-level = 3'),
                     lints=lint_table().replace('unwrap_used = "deny"', 'unwrap_used = { level = "forbid", priority = 2 }'))
        self.assert_pass(self.run_scan())

    def test_local_lints_required_without_inheritance(self):
        self.write('Cargo.toml', '[workspace]\nmembers = ["member"]\n' + PROFILE + lint_table('workspace.lints.clippy'))
        self.package('member', lints='')
        result = self.run_scan()
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('member/Cargo.toml', result.stdout)
        self.assertIn('lints.clippy.pedantic', result.stdout)


if __name__ == '__main__':
    unittest.main()
